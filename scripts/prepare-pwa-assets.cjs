/**
 * Иконки PWA в public/ + конфиг FCM для service worker.
 * Запуск: npm run prepare-pwa
 */
const path = require('path');
const fs = require('fs');
const sharp = require('sharp');

require('dotenv').config({ path: path.join(__dirname, '..', '.env'), quiet: true });

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'assets/images/app-icon.png');
const OUT_DIR = path.join(ROOT, 'public');

const SIZES = [
  { name: 'favicon.png', size: 48 },
  { name: 'apple-touch-icon.png', size: 180 },
  { name: 'icon-192.png', size: 192 },
  { name: 'icon-512.png', size: 512 },
];

function writeFcmSwConfig() {
  const cfg = {
    apiKey: process.env.EXPO_PUBLIC_FIREBASE_API_KEY || '',
    authDomain: process.env.EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN || '',
    projectId: process.env.EXPO_PUBLIC_FIREBASE_PROJECT_ID || '',
    storageBucket: process.env.EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET || '',
    messagingSenderId: process.env.EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || '',
    appId: process.env.EXPO_PUBLIC_FIREBASE_APP_ID || '',
  };
  const out = path.join(OUT_DIR, 'fcm-sw-config.js');
  fs.writeFileSync(
    out,
    `// Auto-generated by prepare-pwa — не редактировать вручную\nself.FIREBASE_CONFIG = ${JSON.stringify(cfg)};\n`,
    'utf8'
  );
  console.log('OK fcm-sw-config.js', cfg.projectId ? `(${cfg.projectId})` : '(пустой Firebase)');
}

async function main() {
  if (!fs.existsSync(SRC)) {
    console.error('Нет исходной иконки:', SRC);
    process.exit(1);
  }
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const { name, size } of SIZES) {
    const out = path.join(OUT_DIR, name);
    await sharp(SRC).resize(size, size, { fit: 'cover' }).png().toFile(out);
    console.log('OK', name);
  }
  writeFcmSwConfig();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
